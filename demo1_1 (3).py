class FileUploadUI(UIComponent):
    """文件上传 UI，自适应 Colab / 本地 Jupyter。"""

    def __init__(self, data_source: DataSource):
        self._ds = data_source

    def build(self, state: AppState) -> widgets.Widget:
        output_area = widgets.Output()

        # 【输入层】：针对不同环境提供文件上传入口"
        if _is_colab():
            from google.colab import files as colab_files
            btn = widgets.Button(description='上传文件', button_style='info')

            def on_click(_):
                with output_area:
                    clear_output(wait=True)
                    print('请在弹出的对话框中选择文件…')
                # 弹出 Colab 专用上传窗口"
                uploaded = colab_files.upload()
                with output_area:
                    clear_output(wait=True)
                    if not uploaded:
                        print('⚠️  未选择任何文件')
                        return
                    # 将上传的文件字典交给数据源处理"
                    self._ds.process_files(uploaded, state, output_area)

            btn.on_click(on_click)
            return widgets.VBox([
                widgets.HTML('<h3>文件导入（支持Excel、CSV）</h3>'),
                btn, output_area
            ])
        else:
            upload_slot = widgets.Box()

            # 迭代处理本地 Jupyter 的上传内容 "
            def _iter(upload_value):
                iterable = upload_value.values() if isinstance(upload_value, dict) else upload_value
                for item in iterable:
                    if isinstance(item, dict):
                        yield item['metadata']['name'], bytes(item['content'])
                    else:
                        yield item.name, item.content.tobytes()

            def _attach():
                wu = widgets.FileUpload(
                    accept='.xls,.xlsx,.csv', multiple=True,
                    description='上传文件', button_style='info'
                )
                def on_upload(change):
                    payload = change['new']
                    if not payload: return
                    with output_area:
                        clear_output(wait=True)
                        self._ds.process_files(dict(_iter(payload)), state, output_area)
                    _attach() # 重新挂载以便多次上传"
                wu.observe(on_upload, names='value')
                upload_slot.children = (wu,)

            _attach()
            return widgets.VBox([
                widgets.HTML('<h3>文件导入（支持Excel、CSV）</h3>'),
                upload_slot, output_area
            ])

class FileDataSource(DataSource):
    """
    【处理层】：从字节流读取数据，并按预定义 Schema 规范化列名。
    """

    # 预设的列名模板（对应 DFD 中的数据字典定义）"
    _SCHEMAS: dict[str, list[str]] = {
        '航班': ['序号','姓名','身份证号','出发地','到达地','起飞时间','到达时间',
                 '航空公司','航班号','座位号','航班日期'],
        '机动车': ['序号','号牌种类','号牌号码','车辆品牌','车身颜色','所有人',
                   '身份证号','c8','c9','c10'],
        '轨迹': ['序号','号牌号码','号牌种类代码名称','通过时间','行政城市',
                 '行政区域','卡口名称'],
        '租赁': ['序号','租赁公司名称','号牌号码','车辆品牌','起租时间','停租时间',
                 '租车人姓名','租车人身份证号码','租车人联系方式'],
        '旅店': ['序号','姓名','身份证号','入住时间','退房时间','旅馆名称','房号',
                 '旅馆地址','所属派出所代码','所属派出所名称','真入住时间','真退房时间'],
    }
    _SCHEMAS['住宿'] = _SCHEMAS['旅店']
    _SCHEMAS['旅业'] = _SCHEMAS['旅店']

    # 需要精简保留的列
    _KEEP_COLUMNS: dict[str, list[str]] = {
        '机动车': ['序号','号牌种类','号牌号码','车辆品牌','车身颜色','所有人','身份证号'],
    }

    def load(self, content: bytes, filename: str) -> pd.DataFrame:
        """DFD - 数据转换：将原始字节流解析为 DataFrame"""
        stream = io.BytesIO(content)
        reader = pd.read_csv if filename.lower().endswith('.csv') else pd.read_excel
        # 跳过前2行（业务逻辑：通常前两行是无效表头或备注）
        return reader(stream, header=None, skiprows=2)

    def apply_schema(self, df: pd.DataFrame, filename: str) -> tuple[pd.DataFrame, bool]:
        """DFD - 数据清洗：通过文件名关键字匹配并强制转换列名"""
        for key, cols in self._SCHEMAS.items():
            if key in filename:
                result = df.copy()
                result.columns = cols
                if key in self._KEEP_COLUMNS:
                    result = result[self._KEEP_COLUMNS[key]]
                return result, True
        return df, False

    def process_files(
        self,
        files: dict[str, bytes],
        state: AppState,
        output: widgets.Output
    ) -> None:
        """DFD - 控制逻辑：循环处理文件流并输出反馈结果"""
        succeeded = failed = 0
        for filename, content in files.items():
            print(f'正在处理: {filename}…')
            try:
                # 1. 载入原始数据
                raw_df = self.load(content, filename)
                # 2. 映射标准列名
                df, matched = self.apply_schema(raw_df, filename)
                if not matched:
                    print('  ⚠️  未识别文件类型，保留原始列名')

                # 3. 输出存储：更新全局状态供其他模块调用
                state["uploaded_frames"][filename] = df
                print(f'  ✅ 上传成功！共 {len(df)} 条数据')
                succeeded += 1
            except Exception as exc:
                print(f'  ❌ 处理失败: {exc}')
                failed += 1

        # 【输出层】：在界面展示最终处理报告
        print(f"\n{'─'*40}")
        print(f'本次结果：成功 {succeeded} 个，失败 {failed} 个')
        print(f'累计已载入文件：{len(state["uploaded_frames"])} 个')

