class DateTimeUtils:
    _FORMATS = ('%Y%m%d%H%M%S', '%Y%m%d%H%M', '%Y%m%d', '%Y-%m-%d %H:%M:%S', '%Y-%m-%d')

    @classmethod
    def robust_to_datetime(cls, series: pd.Series) -> pd.Series:
        """日期转换，兼容各种格式。"""
        warnings.filterwarnings('ignore', category=UserWarning)
        if pd.api.types.is_datetime64_any_dtype(series): return series
        def _parse(v):
            s = str(v).strip().replace('.0', '')
            if not s or s == 'nan': return pd.NaT
            for fmt in cls._FORMATS:
                try:
                    res = pd.to_datetime(s, format=fmt)
                    if not pd.isna(res): return res
                except: continue
            return pd.to_datetime(s, errors='coerce')
        return series.apply(_parse)

    @classmethod
    def clean_time_format(cls, series: pd.Series) -> pd.Series:
        """统一格式化为 YYYY-MM-DD HH:MM。"""
        s = series.astype(str).str.strip().str.replace(r'\.0$', '', regex=True)
        for fmt in cls._FORMATS:
            parsed = pd.to_datetime(s, format=fmt, errors='coerce')
            if parsed.notna().sum() > 0:
                return parsed.dt.strftime('%Y-%m-%d %H:%M')
        return pd.to_datetime(s, errors='coerce').dt.strftime('%Y-%m-%d %H:%M')

    @classmethod
    def fmt_date(cls, series: pd.Series) -> pd.Series:
        """格式化为 YYYY-MM-DD 日期字符串。"""
        return pd.to_datetime(series, errors='coerce').dt.strftime('%Y-%m-%d').fillna('')

    @classmethod
    def resolve_best_col(cls, df: pd.DataFrame, preferred: str, fallback: str) -> str | None:
        """从两个候选列中选出日期数据质量更好的那个。"""
        for col in (preferred, fallback):
            if col in df.columns:
                if cls.robust_to_datetime(df[col]).notna().sum() > len(df) * 0.3:
                    return col
        return None

class IdentityUtils:
    """嫌疑人身份推断工具：通过身份证号判性别和户籍区域。"""
    _NORTH = {'11','12','13','14','15','21','22','23','37','41','61','62','63','64','65'}
    _SOUTH = {'31','32','33','34','35','36','42','43','44','45','46','50','51','52','53','54'}

    @classmethod
    def gender(cls, id_str: str) -> Optional[str]: #callable
        """核心逻辑：看身份证倒数第二位，奇数是男，偶数是女。"""
        s = str(id_str).strip()
        if len(s) < 17 or not s[:17].isdigit(): return None
        return '男性' if int(s[16]) % 2 == 1 else '女性'

    @classmethod
    def region(cls, id_str: str) -> Optional[str]:
        """核心逻辑：根据身份证前两位代码判断属于南方还是北方。"""
        s = str(id_str).strip()
        if len(s) < 2: return None
        prefix = s[:2]
        return '北方' if prefix in cls._NORTH else ('南方' if prefix in cls._SOUTH else None)

    @classmethod
    def apply_filters(cls, df: pd.DataFrame, gender: str, region: str) -> pd.DataFrame:
        """一键画像筛选：给一个大表，按照设定的性别、地域条件自动过滤出嫌疑人。"""
        if df.empty or '身份证号' not in df.columns: return df
        result = df.copy()
        result['_id'] = result['身份证号'].astype(str).str.strip()
        if gender: result = result[result['_id'].apply(cls.gender) == gender]
        if region: result = result[result['_id'].apply(cls.region) == region]
        return result.drop(columns=['_id']).reset_index(drop=True)
