class PlateSearchAnalysis(AnalysisModule):
    """车牌模糊查询分析模块。"""

    def __init__(self, output: widgets.Output):
        self._output = output

    def run(self, state: AppState, pattern: str = '') -> pd.DataFrame:
        # 【处理层 - 1. 数据准备】：从全局状态载入轨迹库
        df_track = next(
            (df for fn, df in state['uploaded_frames'].items() if '轨迹' in fn),
            None
        )
        with self._output:
            clear_output(wait=True)
            if df_track is None:
                print('⚠️ 错误：未找到轨迹数据文件，请先上传！')
                return pd.DataFrame()
            if not pattern:
                print('⚠️ 请输入车牌号片段！')
                return pd.DataFrame()

            # 【处理层 - 2. 匹配算法】：将输入字符串转为大写，并转化为模糊匹配正则
            pattern_upper = pattern.upper()
            regex = '.*'.join(re.escape(c) for c in pattern_upper)
            regex = f'.*{regex}.*'

            # 使用 case=False 或将列转大写进行匹配
            mask = df_track['号牌号码'].str.upper().str.contains(regex, na=False, regex=True)

            # 【处理层 - 3. 结果整理】：按时间倒序排列并锁定匹配结果
            result = df_track[mask].sort_values('通过时间', ascending=False).copy()

            # 【处理层 - 4. 状态同步】：将锁定的车牌和轨迹存入全局状态供后续模块调用
            state['matched_trajectories'] = result
            state['matched_plates']  = list(result['号牌号码'].unique())

            # 【输出层】：渲染反馈信息和分页结果表
            if result.empty:
                print(f'❌ 未找到符合条件的号牌: {pattern_upper}')
            else:
                print(f'🔍 找到 {len(state["matched_plates"])} 辆车，共 {len(result)} 条轨迹。')
                display(UIUtils.paginated_table(result, ''))
                display(UIUtils.export_widget(result, '嫌疑车牌信息.csv.csv'))
        return result

