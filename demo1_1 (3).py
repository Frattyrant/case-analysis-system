class ProgressDriver:
    """
    进度条驱动器。
    封装 show / step / finish / hide 四个操作，
    挂载到任意分析模块的 _progress 属性即可驱动进度条。
    """

    def __init__(self, bar: widgets.IntProgress) -> None:
        self._bar = bar

    # ── 对外接口 ────────────────────────────────
    def step(self, value: int, desc: str | None = None) -> None:
        """推进到第 value 步，可选更新描述文字，并显示进度条。"""
        self._bar.layout.display = ''   # 首次调用时从隐藏变为可见
        self._bar.value = value
        if desc is not None:
            self._bar.description = desc

    def finish(self) -> None:
        """跳到最大值后隐藏，表示分析完成。"""
        self._bar.value = self._bar.max
        self._bar.description = '完成'
        self._bar.layout.display = 'none'

    def error(self) -> None:
        """标记为失败状态后隐藏。"""
        self._bar.bar_style = 'danger'
        self._bar.description = '失败'
        self._bar.layout.display = 'none'

    # ── 空对象（模块在没有进度条时调用不报错）────
    @staticmethod
    def noop() -> '_NoopDriver':
        """返回一个空实现，所有方法调用都静默忽略。"""
        return _NoopDriver()

class _NoopDriver:
    """空实现，让没有挂载进度条的模块调用 step/finish 时不报错。"""
    def step(self, value: int, desc: str | None = None) -> None: pass
    def finish(self) -> None: pass
    def error(self) -> None: pass
