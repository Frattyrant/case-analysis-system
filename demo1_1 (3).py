class CohabitAnalysis(AnalysisModule):
    """同住关联分析模块。"""

    def __init__(self, output: widgets.Output):
        self._output = output

    def run(self, state: AppState) -> pd.DataFrame:
        # 【处理层 - 1. 数据准备】：调取住宿库及租赁分析已锁定的名单
        df_hotel = next(
            (df for fn, df in state['uploaded_frames'].items()
             if any(k in fn for k in ['旅店','住宿','旅业'])),
            pd.DataFrame()
        )
        with self._output:
            clear_output(wait=True)
            if df_hotel.empty:
                print('❌ 错误：未检测到住宿数据库，请先上传数据。')
                return pd.DataFrame()
            if state['df_real_car'].empty:
                print('⚠️ 错误：未检测到已锁定的租赁嫌疑人，请先执行租赁全库分析。')
                return pd.DataFrame()

            suspect_names = state['rental_trajectory_suspects']
            if not suspect_names:
                print('⚠️ 错误：未检测到租赁期内轨迹嫌疑人，请先执行租赁全库分析。')
                return pd.DataFrame()

            # 【处理层 - 辅助】：强力日期转换工具
            def _to_dt(series: pd.Series) -> pd.Series:
                s = series.astype(str).str.strip().str.replace(r'\.0$', '', regex=True)
                return pd.to_datetime(s, errors='coerce', format='%Y%m%d%H%M')

            all_results: list[pd.DataFrame] = []
            # 【处理层 - 2. 核心分析循环】：对每个租车人执行时空关联分析
            for name in suspect_names:
                print(f"\n{'='*60}\n🔍 分析 '{name}' 的同住关联...\n")
                base = df_hotel[df_hotel['姓名'] == name].copy()
                if base.empty:
                    print(f'❌ 住宿库中未找到 "{name}" 的记录，跳过。')
                    continue

                base['dt'] = _to_dt(base['入住时间'])
                pool = df_hotel.copy()
                pool['dt'] = _to_dt(pool['入住时间'])
                pool = pool.dropna(subset=['dt','旅馆名称'])

                hits: list[pd.DataFrame] = []
                for _, row in base.iterrows():
                    # 【处理层 - 核心碰撞算法】：同一旅馆 + 入住时间差 24 小时内
                    window = pd.Timedelta(hours=24)
                    m = (
                        (pool['旅馆名称'] == row['旅馆名称']) &
                        pool['dt'].between(row['dt'] - window, row['dt'] + window)
                    )
                    h = pool[m].copy()
                    h['关联基准人'] = name
                    h['同住关系'] = h['姓名'].apply(lambda x: '本人' if x == name else '潜在同行人')
                    hits.append(h)

                if not hits:
                    print(f'未发现 "{name}" 的同住关联人员。')
                    continue

                # 【处理层 - 3. 结果去重与整理】：移除重复碰撞，并规范时间显示
                df_final = pd.concat(hits).drop_duplicates(
                    subset=['姓名','身份证号','入住时间','旅馆名称']
                )
                df_final['入住时间_标准'] = df_final['dt'].dt.strftime('%Y-%m-%d %H:%M')
                cols = ['姓名','身份证号','同住关系','入住时间_标准','旅馆名称','房号','旅馆地址']
                others = df_final[df_final['同住关系'] != '本人']

                # 【输出层】：渲染该嫌疑人的关联分析报表并提供 CSV 导出
                print(f'✅ "{name}" 关联发现 {len(others)} 名潜在同行人员。')
                display(UIUtils.paginated_table(
                    df_final[cols].sort_values(['入住时间_标准','同住关系']),
                    f' {name} 同住关联分析报告'
                ))
                display(UIUtils.export_widget(df_final[cols], f'{name}_cohort_analysis.csv'))
                all_results.append(df_final[cols])

        return pd.concat(all_results, ignore_index=True) if all_results else pd.DataFrame()

