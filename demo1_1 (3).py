    @staticmethod
    def paginated_table(df: pd.DataFrame, title: str, rows_per_page: int = 5) -> widgets.VBox:
        """分页表格显示：如果数据有几万行，这个组件能保证一次只看5行。"""
        total = len(df)
        total_pages = max(1, (total + rows_per_page - 1) // rows_per_page)
        info_label = widgets.HTML(f'<b>{title}</b>（共 {total} 条，{total_pages} 页）')
        page_input = widgets.BoundedIntText(value=1, min=1, max=total_pages, description='跳转:', layout=widgets.Layout(width='120px'))
        btn_prev = widgets.Button(description='◀ 上一页', layout=widgets.Layout(width='100px'))
        btn_next = widgets.Button(description='下一页 ▶', layout=widgets.Layout(width='100px'))
        page_label = widgets.Label()
        table_out = widgets.Output(layout=widgets.Layout(border='1px solid #e0e0e0', padding='4px'))

        def _show(page: int):
            page_label.value = f'{page} / {total_pages}'
            with table_out:
                clear_output(wait=True)
                if df.empty:
                    print('暂无符合条件的数据')
                    return
                start = (page - 1) * rows_per_page
                display(df.iloc[start: start + rows_per_page].style.hide(axis='index'))

        page_input.observe(lambda c: _show(c['new']), names='value')
        btn_prev.on_click(lambda _: setattr(page_input, 'value', max(1, page_input.value - 1)))
        btn_next.on_click(lambda _: setattr(page_input, 'value', min(total_pages, page_input.value + 1)))
        _show(1)
        nav = widgets.HBox([btn_prev, page_input, page_label, btn_next], layout=widgets.Layout(align_items='center', gap='6px'))
        return widgets.VBox([info_label, nav, table_out])
