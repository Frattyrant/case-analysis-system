class SpatialPenetrationAnalysis(AnalysisModule):
    """时空分析模块"""

    def __init__(self, output: widgets.Output):
        self._output = output

    def run(self, state: AppState, buffer_days: int = 0) -> pd.DataFrame:
        # 【处理层 - 1. 数据准备】：获取轨迹库并验证前置条件
        df_track = next(
            (df for fn, df in state['uploaded_frames'].items() if '轨迹' in fn),
            None
        )
        with self._output:
            clear_output(wait=True)
            if not state['case_points']:
                print('⚠️ 错误：请先录入案发城市和日期。')
                return pd.DataFrame()
            if df_track is None:
                print('⚠️ 错误：未检测到轨迹数据库。')
                return pd.DataFrame()
            if not state['matched_plates']:
                print('⚠️ 错误：当前无锁定的嫌疑车牌，请先执行车牌搜索。')
                return pd.DataFrame()

            # 【处理层 - 2. 时间窗口计算】：根据案发记录自动计算分析的时间跨度（支持动态缓冲区）
            dates = [pd.to_datetime(p[0]) for p in state['case_points']]
            raw_start = min(dates)
            raw_end = max(dates)
            start = raw_start - timedelta(days=buffer_days)
            end = raw_end + timedelta(days=buffer_days)

            # 明确告诉用户本次筛选的时间范围
            print(f'📅 本次筛选时间范围：{start.date()} ～ {end.date()}')
            print(f'📌 原始案发时间范围：{raw_start.date()} ～ {raw_end.date()}')
            print(f'📌 扩大搜索时间：前后各 {buffer_days} 天')
            print('-' * 70)

            # 【处理层 - 3. 空间匹配逻辑】：构建案发城市正则，在轨迹库中匹配卡口或区域名称
            cities = [p[1] for p in state['case_points']]
            loc_re = '|'.join(cities)

            df_track = df_track.copy()
