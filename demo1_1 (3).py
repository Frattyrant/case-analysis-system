class FlightAnalysis(AnalysisModule):
    """航班嫌疑人分析模块：通过案发时间、地点锁定嫌疑人。"""

    def __init__(self, geo: GeoUtils, output: widgets.Output):
        self._geo = geo
        self._output = output

    def run(self, state: AppState) -> pd.DataFrame:
        driver = getattr(self, '_progress', ProgressDriver.noop())
        driver.step(0, '开始加载')

        # 【处理层 - 数据准备】：从全局状态获取航班库和案发信息
        driver.step(1, '读取数据')
        df_raw = next(
            (df.copy() for fn, df in state['uploaded_frames'].items() if '航班' in fn),
            None
        )
        if not state['case_points'] or df_raw is None:
            with self._output:
                print('⚠️ 错误：没找到案发地点数据或航班数据库，请检查前面的步骤。')
            driver.error()
            return pd.DataFrame()

        # 【处理层 - 时间逻辑】：计算分析的时间窗口（首案前 vs 末案后）
        driver.step(2, '时间分析')
        sorted_pts = sorted(state['case_points'], key=lambda x: x[0])
        first_date = pd.to_datetime(sorted_pts[0][0])
        last_date = pd.to_datetime(sorted_pts[-1][0])

        # 【处理层 - 地理逻辑】：将案发城市名转换为省份关键字，用于匹配目的地
        driver.step(3, '地理匹配')
        crime_cities = [p[1] for p in state['case_points']]
        target_provinces = {
            (self._geo.province_of(c) or '').replace('省', '')
            for c in crime_cities
        }

        with self._output:
            clear_output(wait=True)
            print(f'💡 案发时间：{first_date.date()}  末案时间：{last_date.date()}')
            print(f'👤 画像：性别[{state["profile_gender"] or "不限"}]  户籍[{state["profile_region"] or "不限"}]')
            print('=' * 70)

        # 【处理层 - 清洗】：预处理日期和缺失值
        driver.step(4, '清洗数据')
        df_raw['航班日期'] = pd.to_datetime(df_raw['航班日期'], errors='coerce')
        df_raw = df_raw.dropna(subset=['航班日期', '身份证号'])

        relevant_cities: set[str] = set()

        def _is_target(code):
            # 内部逻辑：将机场代码转城市，再转省份进行碰撞
            city = self._geo.city_of_airport(code)
            prov = (self._geo.province_of(city) or '').replace('省', '')
            match = prov in target_provinces
            if match:
                relevant_cities.add(city)
            return match

        # 【处理层 - 空间筛选】：过滤出飞往案发相关区域的航班
        driver.step(5, '筛选表1')
        df_area = df_raw[df_raw['到达地'].apply(_is_target)].copy()

        with self._output:
            print(f' 案发城市附近相关机场城市：{list(relevant_cities)}')

            # 【输出层 - 表1】：筛选首案之前潜入该地区的嫌疑人（且符合画像特征）
            print(f'\n根据首案时间推导出嫌疑人在{first_date}之前到达案发城市 -> 表1')
            df_t1 = IdentityUtils.apply_filters(
                df_area[df_area['航班日期'] <= first_date].copy(),
                state["profile_gender"], state["profile_region"]
            )
            display(UIUtils.paginated_table(df_t1, ''))
            display(UIUtils.export_widget(df_t1, '首案前到达案发城市名单.csv.csv', '导出首案前到达案发城市名单'))

            # 【输出层 - 表2】：筛选末案之后离开的记录
            driver.step(6, '筛选表2')
            print(f'根据首案时间推导出嫌疑人在{last_date}之前离开案发城市 -> 表2')
            df_t2 = IdentityUtils.apply_filters(
                df_raw[df_raw['航班日期'] >= last_date].copy(),
                state["profile_gender"], state["profile_region"]
            )
            display(UIUtils.paginated_table(df_t2, ''))
            display(UIUtils.export_widget(df_t2, '末案后离开案发城市名单.csv', '导出末案后离开案发城市名单'))

            # 【处理层 - 核心碰撞】：计算表1和表2的交集（即：案前飞来，案后飞走的人）
            driver.step(7, '交集计算')
            print('\n根据首案、末案取公共乘客交集 -> 表3')
            if not df_t1.empty and not df_t2.empty:
                df_t3 = pd.merge(
                    df_t1,
                    df_t2[['姓名', '身份证号', '航班号', '航班日期']],
                    on=['姓名', '身份证号'], how='inner',
                    suffixes=('_进入', '_离开')
                )
            else:
                df_t3 = pd.DataFrame()

            # 【输出层 - 表3】：展示最终碰撞出的极高嫌疑名单
            display(UIUtils.paginated_table(df_t3, ''))
            display(UIUtils.export_widget(df_t3, '嫌疑人名单.csv.csv', '导出嫌疑人名单'))

            print('查询完毕')

        driver.step(8, '完成')
        self._hide_progress()
        return df_t3


