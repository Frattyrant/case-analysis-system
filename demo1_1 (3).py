@dataclass
class SlotSpec:
    """
    描述一个业务字段：
      key          – 全局唯一名称，模块自己定，建议加前缀（'traj_matched_plates'）
      default_factory – 无参可调用，返回该字段的初始值
      description  – 可选说明，方便调试时理解每个 key 的含义
    """
    key: str
    default_factory: Callable[[], Any]
    description: str = ""


# ─────────────────────────────────────────────
#  AppState：通用注册容器
# ─────────────────────────────────────────────
class AppState:
    """
    全程序数据核心 —— 通用注册容器版本。

    设计原则
    --------
    * AppState 本身永远不修改字段定义。
    * 各业务模块在自己的文件里调用 `AppState.register(specs)` 声明所需字段。
    * 运行时通过 `state['key']` / `state['key'] = value` 读写，
      也可用属性风格 `state.key` / `state.key = value`（便于兼容旧代码）。
    * `state.reset()` 自动重置所有已注册字段到默认值，无需手动维护。

    快速上手
    --------
    # 1. 模块声明自己的字段（在模块文件顶部执行一次即可）
    AppState.register([
        SlotSpec('traj_matched_plates', list,         '模糊搜索出来的车牌号'),
        SlotSpec('traj_trajectories',   pd.DataFrame, '车牌对应的详细轨迹记录'),
    ])

    # 2. 读写
    state = AppState.instance()
    state['traj_matched_plates'] = ['粤A·12345']
    plates = state['traj_matched_plates']

    # 3. 重置（自动覆盖全部注册字段）
    state.reset()
    """

    # ── 类级别注册表：key -> SlotSpec（所有实例共享同一份 schema）
    _registry: dict[str, SlotSpec] = {}

    # ── 单例（Notebook 场景下通常只需一个全局状态）
    _singleton: "AppState | None" = None

    # ────────────────────────────────
    #  类方法：注册 / 单例获取
    # ────────────────────────────────

    @classmethod
    def instance(cls) -> "AppState":
        """获取全局单例，首次调用时自动创建并初始化所有已注册字段。"""
        if cls._singleton is None:
            cls._singleton = cls()
        return cls._singleton

    @classmethod
    def registered_keys(cls) -> list[str]:
        """返回当前所有已注册的 key，方便调试。"""
        return list(cls._registry.keys())
    @classmethod
    def register(cls, specs: list[SlotSpec]) -> None:
      """
      业务模块调用此方法声明所需字段。
      重复注册同一 key 会跳过（幂等），支持模块热重载场景。
      若单例已存在，新字段会立即补入 _store。
      """
      for spec in specs:
          if spec.key not in cls._registry:
              cls._registry[spec.key] = spec
              if cls._singleton is not None:
                  store = object.__getattribute__(cls._singleton, '_store')
                  store[spec.key] = spec.default_factory()
    # ────────────────────────────────
    #  实例初始化
    # ────────────────────────────────
    def __init__(self) -> None:
        # 运行时数据集，外部不直接访问
        object.__setattr__(self, '_store', {})
        self._init_all()

    def _init_all(self) -> None:
        """按注册表将所有字段初始化为默认值。"""
        store: dict = object.__getattribute__(self, '_store')
        for key, spec in self._registry.items():
            store[key] = spec.default_factory()

    # ────────────────────────────────
    #  读写接口（字典风格）
    # ────────────────────────────────
    def __getitem__(self, key: str) -> Any:
        store: dict = object.__getattribute__(self, '_store')
        if key not in self._registry:
            raise KeyError(f"[AppState] '{key}' 未注册，请先调用 AppState.register()。")
        return store[key]

    def __setitem__(self, key: str, value: Any) -> None:
        store: dict = object.__getattribute__(self, '_store')
        if key not in self._registry:
            raise KeyError(f"[AppState] '{key}' 未注册，请先调用 AppState.register()。")
        store[key] = value

    # ────────────────────────────────
    #  读写接口（属性风格，兼容旧代码）
    # ────────────────────────────────
    def __getattr__(self, key: str) -> Any:
        # __getattr__ 只在普通查找失败时触发，不会影响 _store 等私有属性
        try:
            return self[key]
        except KeyError:
            raise AttributeError(f"[AppState] 属性 '{key}' 未注册。") from None

    def __setattr__(self, key: str, value: Any) -> None:
        if key.startswith('_'):
            object.__setattr__(self, key, value)
        else:
            self[key] = value

    # ────────────────────────────────
    #  其他实用方法
    # ────────────────────────────────
    def reset(self) -> None:
        """一键重置所有已注册字段到默认值。新增模块无需改这里。"""
        self._init_all()

    def snapshot(self) -> dict[str, Any]:
        """返回当前所有字段的浅拷贝，方便调试或序列化。"""
        store: dict = object.__getattribute__(self, '_store')
        return dict(store)

    def __repr__(self) -> str:
        store: dict = object.__getattribute__(self, '_store')
        lines = [f"AppState ({len(self._registry)} 个已注册字段):"]
        for key, spec in self._registry.items():
            val = store.get(key, '<未初始化>')
            preview = repr(val)[:60] + ("…" if len(repr(val)) > 60 else "")
            lines.append(f"  {key:<35} = {preview}")
            if spec.description:
                lines.append(f"  {'':35}   # {spec.description}")
        return "\n".join(lines)

